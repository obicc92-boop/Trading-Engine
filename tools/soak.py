"""Time-compressed soak test — engine robustness, NOT strategy performance.

Runs the equivalent of weeks of continuous operation in a couple of minutes by advancing a
simulated clock instead of sleeping. Every cycle is the real `Engine.cycle()` against the
real rule, the real store and the real simulated broker, with the engine torn down and
rebuilt from disk at intervals, as a redeploy would.

WHAT THIS PROVES
    The loop survives thousands of cycles without crashing or leaking, the rule acts once a
    day and only as the closes say, the books keep matching the cash, and holdings survive
    restarts exactly.

WHAT THIS PROVES NOTHING ABOUT
    Whether the strategy makes money. Prices here are generated by `SyntheticMarket`, which
    is a plausible-looking fake, not a market. The P&L this produces is an artefact of that
    generator and means exactly nothing. It is not a backtest and must never be quoted as
    one — `tools/backtest.py` replays real history.

    python tools/soak.py --days 30
"""

from __future__ import annotations

import argparse
import gc
import resource
import sys
import traceback
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from helm import doctrine  # noqa: E402
from helm.config import Config  # noqa: E402

# The simulated clock, in unix milliseconds. One mutable cell so every patched reference
# sees the same value.
CLOCK = [0]
DAY = 86_400_000


def install_clock() -> None:
    """Point every module's `now_ms` at the simulated clock.

    Modules import `now_ms` by name, so rebinding `helm.models.now_ms` alone would miss
    all of them — each module's own reference has to be replaced.
    """
    import helm.engine
    import helm.risk

    def now_ms() -> int:
        return CLOCK[0]

    for name, module in list(sys.modules.items()):
        if name.startswith("helm") and hasattr(module, "now_ms"):
            setattr(module, "now_ms", now_ms)

    # The day boundary has to move with the simulated clock too. Left alone, the real
    # calendar would treat every simulated day as the same day, and the rule would decide
    # once and never again.
    def day_start(now=None):
        moment = datetime.fromtimestamp(CLOCK[0] / 1000, timezone.utc)
        return moment.replace(hour=0, minute=0, second=0, microsecond=0)

    helm.engine.utc_day_start = day_start
    helm.risk.utc_day_start = day_start


def rss_mb() -> float:
    # ru_maxrss is kilobytes on Linux but bytes on macOS, which otherwise reads 50MB as 50GB.
    peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    return peak / (1024 * 1024) if sys.platform == "darwin" else peak / 1024


def clear_database(path: Path) -> None:
    """Remove this database and its sqlite sidecars — and nothing else.

    Deliberately never removes the containing directory. `--db data/helm.db` is the obvious
    thing to type, and that is the live deployment's own database: taking its parent would
    delete the record of every coin held, along with the KILL file, while the coins stayed
    on the exchange with nothing managing them.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    for stale in (path, *(path.with_name(path.name + suffix) for suffix in ("-wal", "-shm"))):
        stale.unlink(missing_ok=True)


def books_gap(engine) -> float:
    """Cash plus what the open positions cost, against the start plus everything realised.

    Every purchase moves its cost out of cash and every sale books its proceeds less that
    cost, so the two sides must agree to the cent for as long as the engine runs.
    """
    cash = engine.broker.balances().get(engine.config.quote, 0.0)
    held = sum(position.cost_held() for position in engine.positions)
    return cash + held - (engine.config.starting_equity + engine.store.total_realized())


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--days", type=float, default=30.0)
    parser.add_argument("--step-minutes", type=int, default=15,
                        help="simulated time between cycles")
    parser.add_argument("--db", default="/tmp/helm-soak/soak.db")
    parser.add_argument("--restart-every", type=int, default=200,
                        help="rebuild the Engine from disk every N cycles, to prove that "
                             "state survives a redeploy")
    parser.add_argument("--start-at", type=int, default=None,
                        help="epoch ms to start the simulated clock at. Synthetic prices are a "
                             "pure function of time, so pinning this pins the whole price path "
                             "and makes a run exactly reproducible. Defaults to now, which walks "
                             "a fresh path every time")
    args = parser.parse_args()

    clear_database(Path(args.db))

    import helm.engine as engine_module

    started_at = args.start_at if args.start_at is not None else int(
        datetime.now(timezone.utc).timestamp() * 1000
    )
    CLOCK[0] = started_at
    install_clock()

    config = Config()
    config.db_path = args.db
    config.venue = "synthetic"
    config.telegram_token = ""           # a soak must never page anyone

    engine = engine_module.Engine(config)

    cycles = int(args.days * 24 * 60 / args.step_minutes)
    step_ms = args.step_minutes * 60_000

    errors: list[str] = []
    restarts = 0
    worst_gap = 0.0
    peak_equity = config.starting_equity
    rss_samples: list[float] = []

    print(f"soaking {args.days:g} simulated days — {cycles} cycles at "
          f"{args.step_minutes}m intervals\n"
          f"price path: --start-at {started_at}\n")

    for i in range(1, cycles + 1):
        CLOCK[0] += step_ms
        try:
            engine.cycle()
        except Exception as exc:
            errors.append(f"cycle {i}: {type(exc).__name__}: {exc}")
            traceback.print_exc()

        worst_gap = max(worst_gap, abs(books_gap(engine)))
        peak_equity = max(peak_equity, engine.account_state().equity)

        if i % args.restart_every == 0:
            # Prove the engine can be killed and restarted while holding coins without
            # losing track of them — the thing that actually happens on a redeploy.
            before = {p.id: (p.symbol, p.qty, p.cost) for p in engine.positions}
            decided = engine.store.get("decided_day")
            engine = engine_module.Engine(config)
            engine._restore_positions()
            restarts += 1
            after = {p.id: (p.symbol, p.qty, p.cost) for p in engine.positions}
            if before != after:
                errors.append(f"cycle {i}: holdings lost across restart — {before} != {after}")
            if engine.store.get("decided_day") != decided:
                errors.append(f"cycle {i}: the decided day was lost across a restart")

        if i % max(1, cycles // 10) == 0:
            state = engine.account_state()
            rss_samples.append(rss_mb())
            day = i * args.step_minutes / 1440
            print(f"  day {day:5.1f}  equity {state.equity:7.2f}  held {len(engine.positions)}  "
                  f"closed {len(engine.store.all_closed()):3d}  rss {rss_samples[-1]:5.1f}MB")

    # ---- report --------------------------------------------------------------------------
    closed = engine.store.all_closed()
    every = closed + [{"symbol": p.symbol, "opened_at": p.opened_at, "cost": p.cost} for p in engine.positions]
    decisions = engine.store.decisions(100_000)
    db_kb = Path(args.db).stat().st_size / 1024

    print("\n" + "=" * 64)
    print("ENGINE HEALTH")
    print("=" * 64)
    print(f"  cycles run           {cycles}")
    print(f"  errors               {len(errors)}")
    print(f"  restarts survived    {restarts}")
    print(f"  memory               {rss_samples[0]:.1f}MB -> {rss_samples[-1]:.1f}MB")
    print(f"  database             {db_kb:.0f}KB after {len(decisions)} decisions")

    print("\n" + "=" * 64)
    print("RULE COMPLIANCE  (these must all hold)")
    print("=" * 64)
    violations = []

    strays = sorted({row["symbol"] for row in every} - set(doctrine.SYMBOLS))
    if strays:
        violations.append(f"bought {', '.join(strays)}, which the doctrine does not trade")

    held_now = [p.symbol for p in engine.positions]
    if len(held_now) != len(set(held_now)):
        violations.append(f"more than one position in one coin: {held_now}")

    per_day: dict[tuple[int, str], int] = {}
    for row in decisions:
        per_day[(row["day"], row["symbol"])] = per_day.get((row["day"], row["symbol"]), 0) + 1
    repeated = sum(1 for count in per_day.values() if count > 1)
    if repeated:
        violations.append(f"{repeated} coin-days decided more than once")

    wrong_way = [row for row in decisions if (row["action"] == "BUY" and not row["on"])
                 or (row["action"] == "SELL" and row["on"])]
    if wrong_way:
        violations.append(f"{len(wrong_way)} trades against what the close said")

    # The first decision runs as soon as the engine starts, whatever the hour — it acts on
    # the latest close, as a restart in production does. After that, only just past midnight.
    first_cycle = started_at + step_ms
    late = [row for row in every if row["opened_at"] > first_cycle
            and row["opened_at"] % DAY > step_ms]
    if late:
        violations.append(f"{len(late)} purchases outside the first cycle after a close")

    oversized = [row for row in every
                 if row["cost"] > doctrine.ENTRY_FRACTION * peak_equity * 1.001]
    if oversized:
        violations.append(f"{len(oversized)} purchases larger than a quarter of the account")

    if worst_gap > 1e-6:
        violations.append(f"the books drifted from the cash by {worst_gap:.6f}")

    print(f"  coins traded               {', '.join(sorted({row['symbol'] for row in every})) or 'none'}")
    print(f"  coin-days decided twice    {repeated}")
    print(f"  trades against the close   {len(wrong_way)}")
    print(f"  purchases off the close    {len(late)}")
    print(f"  oversized purchases        {len(oversized)}")
    print(f"  books vs cash, worst gap   {worst_gap:.2e}")
    print(f"  {'NO VIOLATIONS' if not violations else 'VIOLATIONS: ' + '; '.join(violations)}")

    print("\n" + "=" * 64)
    print("ACTIVITY  (behaviour, not performance — prices are fake)")
    print("=" * 64)
    buys = sum(1 for row in decisions if row["action"] == "BUY")
    sells = sum(1 for row in decisions if row["action"] == "SELL")
    print(f"  daily decisions recorded   {len(decisions)}")
    print(f"  purchases / sales          {buys} / {sells}")
    print(f"  coins held at the end      {', '.join(held_now) or 'none'}")
    if closed:
        days = sorted(((row["closed_at"] or 0) - (row["opened_at"] or 0)) / DAY for row in closed)
        print(f"  median hold                {days[len(days) // 2]:.1f} days")

    if errors:
        print("\nERRORS")
        for error in errors[:10]:
            print(f"  {error}")

    if errors or violations:
        # An unreproducible failure is a failure you will eventually learn to ignore.
        print("\nreplay this exact run with:")
        print(f"  python tools/soak.py --days {args.days:g} --step-minutes {args.step_minutes} "
              f"--restart-every {args.restart_every} --start-at {started_at}")

    print()
    gc.collect()
    return 1 if (errors or violations) else 0


if __name__ == "__main__":
    raise SystemExit(main())
