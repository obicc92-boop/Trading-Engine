"""Time-compressed soak test — engine robustness, NOT strategy performance.

Runs the equivalent of several days of continuous operation in a couple of minutes by
advancing a simulated clock instead of sleeping. Every cycle is the real `Engine.cycle()`
against the real risk rails, the real exit ladder and the real store.

WHAT THIS PROVES
    The loop survives thousands of cycles without crashing or leaking, positions are
    opened/managed/closed coherently, the rails fire when they should, and the database
    stays consistent across restarts.

WHAT THIS PROVES NOTHING ABOUT
    Whether the strategy makes money. Prices here are generated by `SyntheticMarket`, which
    is a plausible-looking fake, not a market. The P&L this produces is an artefact of that
    generator and means exactly nothing. It is not a backtest and must never be quoted as
    one. The decision layer is stubbed too — see `StubDesk` below.

    python tools/soak.py --days 7
"""

from __future__ import annotations

import argparse
import gc
import resource
import sys
import traceback
from datetime import datetime, timedelta, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from helm import doctrine  # noqa: E402
from helm.config import Config  # noqa: E402
from helm.models import Verdict  # noqa: E402

# The simulated clock, in unix milliseconds. One mutable cell so every patched reference
# sees the same value.
CLOCK = [0]


def install_clock() -> None:
    """Point every module's `now_ms` at the simulated clock.

    Modules import `now_ms` by name, so rebinding `helm.models.now_ms` alone would miss
    all of them — each module's own reference has to be replaced.
    """
    import helm.engine
    import helm.risk

    def now_ms() -> int:
        return CLOCK[0]

    for name, module in list(sys.modules.items()):
        if name.startswith("helm") and hasattr(module, "now_ms"):
            setattr(module, "now_ms", now_ms)

    # Day and week boundaries have to move with the simulated clock too. Left alone, the
    # real calendar would treat every simulated day as "today", the daily entry cap would
    # never reset, and the soak would stop trading after day one.
    def day_start(now=None):
        moment = datetime.fromtimestamp(CLOCK[0] / 1000, timezone.utc)
        return moment.replace(hour=0, minute=0, second=0, microsecond=0)

    def week_start(now=None):
        start = day_start()
        return start - timedelta(days=start.weekday())

    helm.engine.utc_day_start = day_start
    helm.engine.utc_week_start = week_start
    helm.risk.utc_day_start = day_start
    helm.risk.utc_week_start = week_start


class StubDesk:
    """Stands in for the decision layer, which needs an API key this environment lacks.

    Not an impersonation of the real thing — it is a crude score-proportional approver, so
    the soak exercises the full entry path (verdict -> rails -> sizing -> order) with a
    plausible mix of approvals, refusals and reduced sizes. Any P&L it produces is doubly
    meaningless: fake prices judged by a fake desk.
    """

    def __init__(self) -> None:
        self.approved = 0
        self.declined = 0

    def __call__(self, candidate, state, recent, scan) -> Verdict:
        score = candidate.score
        if score < 66:
            self.declined += 1
            return Verdict(go=False, conviction=int(score / 2), size_multiplier=0.25,
                           stop_override=None, thesis="Stub: below the conviction bar.",
                           invalidation="", source="stub")
        self.approved += 1
        multiplier = 1.0 if score >= 72 else 0.6
        return Verdict(go=True, conviction=int(min(85, score)), size_multiplier=multiplier,
                       stop_override=None, thesis=f"Stub approval at score {score:.0f}.",
                       invalidation="Stub invalidation.", source="stub")


def rss_mb() -> float:
    # ru_maxrss is kilobytes on Linux but bytes on macOS, which otherwise reads 50MB as 50GB.
    peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    return peak / (1024 * 1024) if sys.platform == "darwin" else peak / 1024


def clear_database(path: Path) -> None:
    """Remove this database and its sqlite sidecars — and nothing else.

    Deliberately never removes the containing directory. `--db data/helm.db` is the obvious
    thing to type, and that is the live deployment's own database: taking its parent would
    delete every open position's stop and target, along with the KILL file, while the coins
    stayed on the exchange with nothing managing them.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    for stale in (path, *(path.with_name(path.name + suffix) for suffix in ("-wal", "-shm"))):
        stale.unlink(missing_ok=True)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--days", type=float, default=7.0)
    parser.add_argument("--step-minutes", type=int, default=15,
                        help="simulated time between cycles")
    parser.add_argument("--db", default="/tmp/helm-soak/soak.db")
    parser.add_argument("--restart-every", type=int, default=200,
                        help="rebuild the Engine from disk every N cycles, to prove that "
                             "state survives a redeploy")
    parser.add_argument("--start-at", type=int, default=None,
                        help="epoch ms to start the simulated clock at. Synthetic prices are a "
                             "pure function of time, so pinning this pins the whole price path "
                             "and makes a run exactly reproducible. Defaults to now, which walks "
                             "a fresh path every time")
    args = parser.parse_args()

    clear_database(Path(args.db))

    import helm.engine as engine_module

    started_at = args.start_at if args.start_at is not None else int(
        datetime.now(timezone.utc).timestamp() * 1000
    )
    CLOCK[0] = started_at
    install_clock()

    config = Config()
    config.db_path = args.db
    config.venue = "synthetic"
    config.scan_every_cycles = 1

    desk = StubDesk()
    engine = engine_module.Engine(config)
    engine.brain.judge_entry = desk

    cycles = int(args.days * 24 * 60 / args.step_minutes)
    step_ms = args.step_minutes * 60_000

    errors: list[str] = []
    restarts = 0
    peak_open = 0
    rss_samples: list[float] = []

    print(f"soaking {args.days:g} simulated days — {cycles} cycles at "
          f"{args.step_minutes}m intervals\n"
          f"price path: --start-at {started_at}\n")

    for i in range(1, cycles + 1):
        CLOCK[0] += step_ms
        try:
            engine.cycle()
        except Exception as exc:
            errors.append(f"cycle {i}: {type(exc).__name__}: {exc}")
            traceback.print_exc()

        peak_open = max(peak_open, len(engine.positions))

        if i % args.restart_every == 0:
            # Prove the engine can be killed and restarted mid-trade without losing the
            # plan for an open position — the thing that actually happens on a redeploy.
            open_before = {p.id: (p.stop, p.qty) for p in engine.positions}
            engine.brain._asked.clear()
            engine = engine_module.Engine(config)
            engine.brain.judge_entry = desk
            engine._restore_positions()
            restarts += 1
            open_after = {p.id: (p.stop, p.qty) for p in engine.positions}
            if open_before != open_after:
                errors.append(
                    f"cycle {i}: state lost across restart — {open_before} != {open_after}"
                )

        if i % max(1, cycles // 10) == 0:
            state = engine.account_state()
            rss_samples.append(rss_mb())
            day = i * args.step_minutes / 1440
            print(f"  day {day:5.1f}  equity {state.equity:7.2f}  open {len(engine.positions)}  "
                  f"closed {len(engine.store.all_closed()):3d}  dd {state.drawdown*100:4.1f}%  "
                  f"rss {rss_samples[-1]:5.1f}MB")

    # ---- report --------------------------------------------------------------------------
    closed = engine.store.all_closed()
    state = engine.account_state()
    decisions = engine.store.decisions(10_000)
    db_kb = Path(args.db).stat().st_size / 1024

    print("\n" + "=" * 64)
    print("ENGINE HEALTH")
    print("=" * 64)
    print(f"  cycles run           {cycles}")
    print(f"  errors               {len(errors)}")
    print(f"  restarts survived    {restarts}")
    print(f"  memory               {rss_samples[0]:.1f}MB -> {rss_samples[-1]:.1f}MB")
    print(f"  database             {db_kb:.0f}KB after {len(decisions)} decisions")
    print(f"  peak open positions  {peak_open} (limit {doctrine.MAX_OPEN_POSITIONS})")

    print("\n" + "=" * 64)
    print("RULE COMPLIANCE  (these must all hold)")
    print("=" * 64)
    violations = []
    if peak_open > doctrine.MAX_OPEN_POSITIONS:
        violations.append(f"held {peak_open} positions, limit is {doctrine.MAX_OPEN_POSITIONS}")

    worst_loss = min((row["realized_pnl"] or 0.0) for row in closed) if closed else 0.0
    worst_r = min((row["r_multiple"] or 0.0) for row in closed) if closed else 0.0
    if worst_r < -2.5:
        violations.append(f"a trade lost {worst_r:.2f}R — stops are not holding")

    by_day: dict[str, int] = {}
    for row in closed:
        day = datetime.fromtimestamp((row["opened_at"] or 0) / 1000, timezone.utc).date().isoformat()
        by_day[day] = by_day.get(day, 0) + 1
    busiest = max(by_day.values()) if by_day else 0
    if busiest > doctrine.MAX_ENTRIES_PER_DAY:
        violations.append(f"{busiest} entries in one day, cap is {doctrine.MAX_ENTRIES_PER_DAY}")

    print(f"  max concurrent positions   {peak_open} / {doctrine.MAX_OPEN_POSITIONS}")
    print(f"  max entries in a day       {busiest} / {doctrine.MAX_ENTRIES_PER_DAY}")
    print(f"  worst single trade         {worst_loss:+.2f} ({worst_r:+.2f}R)")
    print(f"  {'NO VIOLATIONS' if not violations else 'VIOLATIONS: ' + '; '.join(violations)}")

    print("\n" + "=" * 64)
    print("ACTIVITY  (behaviour, not performance — prices are fake)")
    print("=" * 64)
    print(f"  candidates reaching the desk   {len(decisions)}")
    print(f"  stub approved / declined       {desk.approved} / {desk.declined}")
    print(f"  trades completed               {len(closed)}")
    if closed:
        reasons: dict[str, int] = {}
        for row in closed:
            reasons[row["exit_reason"]] = reasons.get(row["exit_reason"], 0) + 1
        print("  exit reasons:")
        for reason, count in sorted(reasons.items(), key=lambda kv: -kv[1]):
            print(f"      {reason.lower().replace('_',' '):22} {count}")
        holding = [
            ((row["closed_at"] or 0) - (row["opened_at"] or 0)) / 3_600_000 for row in closed
        ]
        print(f"  median hold                    {sorted(holding)[len(holding)//2]:.1f}h")

    if errors:
        print("\nERRORS")
        for error in errors[:10]:
            print(f"  {error}")

    if errors or violations:
        # An unreproducible failure is a failure you will eventually learn to ignore.
        print("\nreplay this exact run with:")
        print(f"  python tools/soak.py --days {args.days:g} --step-minutes {args.step_minutes} "
              f"--restart-every {args.restart_every} --start-at {started_at}")

    print()
    gc.collect()
    return 1 if (errors or violations) else 0


if __name__ == "__main__":
    raise SystemExit(main())
